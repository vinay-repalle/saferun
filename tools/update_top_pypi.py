"""Regenerate saferun/data/top_pypi.txt, the offline list of popular PyPI package names used by `saferun check-names`.

    python tools/update_top_pypi.py                 download the dataset (public data, nothing about any project is sent)
    python tools/update_top_pypi.py --input FILE    use an already downloaded top-pypi-packages.min.json

Source: https://hugovk.github.io/top-pypi-packages/ (download counts of the last 30 days). Only the names are kept: normalised
(PEP 503), duplicates and anything that is not a valid name dropped, most downloaded first. Run it before a release and review
the diff (`git diff --stat saferun/data/top_pypi.txt`); the file header records the source and the date of the dataset.
"""
from __future__ import annotations

import argparse
import json
import re
import urllib.request
from pathlib import Path

URL = "https://hugovk.github.io/top-pypi-packages/top-pypi-packages.min.json"
OUT = Path(__file__).resolve().parent.parent / "saferun" / "data" / "top_pypi.txt"
VALID = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def build(doc: dict, count: int) -> str:
    names: list[str] = []
    seen: set[str] = set()
    for row in sorted(doc["rows"], key=lambda r: -int(r["download_count"])):
        n = re.sub(r"[-_.]+", "-", str(row["project"])).lower()
        if VALID.fullmatch(n) and n not in seen:
            seen.add(n)
            names.append(n)
        if len(names) == count:
            break
    date = str(doc["last_update"]).split()[0]
    header = [f"# source: {URL}", f"# date: {date}", f"# count: {len(names)}",
              "# Popular PyPI package names, normalised (PEP 503), most downloaded first. Generated by tools/update_top_pypi.py; do not edit by hand."]
    return "\n".join(header + names) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", help="a downloaded top-pypi-packages.min.json instead of downloading")
    ap.add_argument("--count", type=int, default=10000, help="number of names to keep (default: 10000)")
    ap.add_argument("--output", default=str(OUT))
    args = ap.parse_args()
    if args.input:
        doc = json.loads(Path(args.input).read_text(encoding="utf-8"))
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            doc = json.loads(r.read(50_000_000))
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build(doc, args.count), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({args.count} names requested)")


if __name__ == "__main__":
    main()
